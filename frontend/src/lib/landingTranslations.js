export function detectBrowserLanguage() {
  const browserLang = (
    navigator.language ||
    (navigator.languages && navigator.languages[0]) ||
    "es"
  )
    .toLowerCase()
    .split("-")[0];

  const found = SUPPORTED_LANGUAGES.find((l) => l.code === browserLang);
  return found ? found.code : "en"; // Si no es español ni ninguno soportado, inglés por defecto para turistas
}

